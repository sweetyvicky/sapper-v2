import assert from 'node:assert/strict';
import { action, modelSummary } from '../../lib/pentest/operator_web/ui.js';
const box={textContent:'',classList:{add(){},remove(){}}},trigger={disabled:false};
await action(box,async()=>{box.textContent='';},trigger);
assert.equal(box.textContent,'操作成功','A form reset after successful save must still acknowledge success');
assert.equal(trigger.disabled,false);
assert.equal(modelSummary({model_profile_id:null,role_profiles:{Commander:'commander'}},[{id:'commander',name:'实际规划配置'}]).includes('Commander（规划）：实际规划配置'),true);
assert.equal(modelSummary({model_profile_id:null,role_profiles:{Scout:'scout'}},[{id:'scout',name:'观察模型'}]).includes('基础观察'),false);
assert.equal(modelSummary({model_profile_id:null,role_profiles:{}}),'基础观察（不调用模型）');
console.log('PASS: save acknowledgement survives form reset; role-only model modes remain visible');
import * as ui from '../../lib/pentest/operator_web/ui.js';
assert.equal(typeof ui.roundOptions,'function','Older selected rounds must stay in the selector after loading history');
const rounds=ui.roundOptions([{id:'recent',created_at:1,status:'completed'}],'older');
assert.deepEqual(rounds.map(([id])=>id),['recent','older']);
assert.equal(rounds[1][1].includes('历史轮次'),true);
const many=Array.from({length:50},(_,i)=>({id:'recent-'+i,created_at:1,status:'completed'}));
assert.equal(ui.roundOptions(many,'older').length,51);
assert.equal(ui.roundOptions(many,'older')[0][1].includes('最近第 1 轮'),true);
console.log('PASS: historical selected round retained outside latest 50; recent ordering labelled honestly');
